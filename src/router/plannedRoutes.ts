/**
 * 화면 .vue 파일 맵 (`views/{도메인}/{화면ID}/{화면ID}.vue`).
 * eager 가 아니라서 지연 로딩되고, 아직 없는 화면은 키 자체가 없다.
 */
const pageModules = import.meta.glob<{ default: Component }>('../views/*/*/*.vue')

/** 'PC-COM-2206' -> 'com' (폴더명). 화면ID 가운데 세 글자가 도메인이다. */
function domainOf(screenId: string): string {
  return screenId.split('-')[1]?.toLowerCase() ?? ''
}

/**
 * 예정 화면 라우트를 만든다.
 *
 * @param taken 이미 등록된 라우트 name 집합. 여기 있는 화면ID 는 건너뛴다 —
 *              router/index.ts 에 직접 적힌 라우트와 name 이 겹치면
 *              vue-router 가 중복 경고를 내고 뒤쪽이 앞쪽을 덮는다.
 */
export function buildPlannedRoutes(taken: Set<string>): RouteRecordRaw[] {
  return plannedScreens
    .filter(([id]) => !taken.has(id))
    .map(([id, title]) => {
      const domain = domainOf(id)
      const loader = pageModules[`../views/${domain}/${id}/${id}.vue`]
      return {
        path: `/views/${domain}/${id}`,
        name: id,
        component: loader ?? NotReady,
        meta: {
          layout: 'WorkLayout',
          title,
          /** 아직 화면 파일이 없어 NotReady 로 대체된 라우트 */
          planned: !loader,
        },
      }
    })
}
